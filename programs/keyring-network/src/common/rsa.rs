use anchor_lang::prelude::*;
use anchor_lang::solana_program::hash;

use crypto_bigint::{NonZero, U1024};

// Pre-computed PKCS#1 v1.5 padding template for SHA-256 (128 bytes total)
// This avoids runtime construction and reduces compute units significantly
const PKCS1_SHA256_PADDING_TEMPLATE: [u8; 128] = [
    // 0x00 0x01 (2 bytes)
    0x00, 0x01,
    // 0xFF padding (2 bytes)
    0xFF, 0xFF,
    // 0xFF padding (74 bytes)
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    // ASN.1 DER encoding for SHA-256 (20 bytes)
    0x00, 0x30, 0x31, 0x30, 0x0D, 0x06, 0x09, 0x60,
    0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01,
    0x05, 0x00, 0x04, 0x20,
    // Hash placeholder (32 bytes) - will be overwritten with actual hash
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
];

pub fn verify_rsa_signature(
    modulus: Vec<u8>,
    signature: Vec<u8>,
    message: Vec<u8>,
) -> Result<bool> {
    // Early validation to fail fast and save compute units
    if modulus.len() != 128 || signature.len() != 128 {
        return Ok(false);
    }

    // Convert inputs to U1024 with proper error handling
    let modulus = NonZero::new(U1024::from_be_slice(&modulus)).unwrap();
    
    let signature = NonZero::new(U1024::from_be_slice(&signature)).unwrap();

    // Hash the message
    let message_hash = hash::hash(message.as_slice());


    let mut padded_bytes = PKCS1_SHA256_PADDING_TEMPLATE;
    // Copy the actual hash into the last 32 bytes
    padded_bytes[96..128].copy_from_slice(message_hash.as_ref());

    let padded = U1024::from_be_slice(&padded_bytes);

    let result = signature.mul_mod_vartime(&signature.mul_mod_vartime(&signature, &modulus), &modulus);

    Ok(result == padded)
}